class fifo_transaction;

    // =====================================================
    // FIFO CONTROL SIGNALS
    // =====================================================

    rand logic wr_en;
    rand logic rd_en;


    // =====================================================
    // WRITE DATA
    // =====================================================

    rand logic [7:0] data;


    // =====================================================
    // ACTUAL READ DATA
    // =====================================================

    logic [7:0] read_data;


    // =====================================================
    // OPERATION ACCEPTANCE
    // =====================================================

    logic write_valid;
    logic read_valid;


    // =====================================================
    // DATA CONSTRAINT
    // =====================================================

    constraint valid_data {

        data inside {[0:255]};

    }

endclass
